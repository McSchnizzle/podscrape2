#!/usr/bin/env python3
"""
Digest Quality Evaluation Script

Evaluates digest scripts generated by different models using a standardized rubric.
Uses Claude to analyze and grade each digest across multiple quality dimensions.
"""

import os
import sys
import json
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Optional

# Add parent directory to path
sys.path.insert(0, str(Path(__file__).parent.parent))

